import { chromium } from '@playwright/test'

const browser = await chromium.launch({ headless: true, executablePath: 'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe' })
const context = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })
const page = await context.newPage()
await page.addInitScript(() => {
  window.__touchTrace = []
  for (const type of ['pointerdown', 'pointermove', 'pointerup', 'touchstart', 'touchmove', 'touchend', 'touchcancel']) {
    window.addEventListener(type, event => {
      const target = event.target instanceof Element ? event.target.closest('.system-object, .cluster-system-node') : null
      window.__touchTrace.push({ type, touches: 'touches' in event ? event.touches.length : null, target: target?.getAttribute('data-object-id') ?? target?.getAttribute('data-system-id') ?? null, x: event.clientX ?? null, y: event.clientY ?? null })
    }, true)
  }
})
await page.goto('http://127.0.0.1:3127/', { waitUntil: 'domcontentloaded' })
await page.locator('.cluster-map-svg .cluster-system-node').first().click()
await page.locator('.system-map-svg').waitFor({ state: 'visible' })
await page.locator('.b-tool-rail .rail-button[title="Move / Modify"]').click()
const object = page.locator('.system-map-svg .system-object').first()
const cdp = await context.newCDPSession(page)
await cdp.send('Emulation.setTouchEmulationEnabled', { enabled: true, maxTouchPoints: 2 })
const point = async (dx = 0, dy = 0, id = 1) => {
  const box = await object.boundingBox()
  return { x: Math.round(box.x + box.width / 2 + dx), y: Math.round(box.y + box.height / 2 + dy), id, radiusX: 5, radiusY: 5, force: 1 }
}
const beforeFirst = await object.getAttribute('transform')
await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [await point()] })
await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [await point(22, 5)] })
await page.waitForTimeout(120)
const afterFirstPreview = await object.getAttribute('transform')
await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
await page.waitForTimeout(160)
const afterFirstCommit = await object.getAttribute('transform')
const box = await page.locator('.system-map-svg').boundingBox()
const first = await point(0, 0, 2)
const second = { ...first, x: Math.min(box.x + box.width - 24, first.x + 72), id: 3 }
const beforePinch = await object.getAttribute('transform')
const viewBeforePinch = await page.locator('.system-map-svg .system-map-content').getAttribute('transform')
await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [first] })
await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ ...first, x: first.x + 16, y: first.y + 2 }] })
await page.waitForTimeout(100)
const previewBeforeSecond = await object.getAttribute('transform')
await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ ...first, x: first.x + 16, y: first.y + 2 }, second] })
await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ ...first, x: first.x + 16, y: first.y + 2 }, { ...second, x: second.x + 60 }] })
await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [second] })
await page.waitForTimeout(80)
const afterSecondLift = await object.getAttribute('transform')
const viewAfterSecondLift = await page.locator('.system-map-svg .system-map-content').getAttribute('transform')
await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ ...first, x: first.x + 30, y: first.y + 18 }] })
await page.waitForTimeout(100)
const afterRemainingFinger = await object.getAttribute('transform')
const viewAfterRemainingFinger = await page.locator('.system-map-svg .system-map-content').getAttribute('transform')
await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
await page.waitForTimeout(700)
const viewAfterPinch = await page.locator('.system-map-svg .system-map-content').getAttribute('transform')
const afterPinch = await object.getAttribute('transform')
const nextPoint = await point(0, 0, 4)
const beforeNext = await object.getAttribute('transform')
await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [nextPoint] })
await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ ...nextPoint, x: nextPoint.x + 22, y: nextPoint.y + 5 }] })
await page.waitForTimeout(120)
const nextPreview = await object.getAttribute('transform')
await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
await page.waitForTimeout(200)
const nextCommit = await object.getAttribute('transform')
const trace = await page.evaluate(() => window.__touchTrace)
console.log(JSON.stringify({ beforeFirst, afterFirstPreview, afterFirstCommit, beforePinch, previewBeforeSecond, afterPinch, viewBeforePinch, viewAfterPinch, afterSecondLift, viewAfterSecondLift, afterRemainingFinger, viewAfterRemainingFinger, beforeNext, nextPreview, nextCommit, trace }, null, 2))
await context.close()
await browser.close()
