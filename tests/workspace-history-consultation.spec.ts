test('History consultation stays read only across Undo and Redo and returns focus on compact screens', async ({ page }) => {
  await createSingleSystemWorkspace(page)
  await page.setViewportSize({ width: 390, height: 844 })
  const historyButton = page.getByRole('button', { name: 'History', exact: true })
  const historyControls = page.locator('.workspace-history-controls')
  const undo = historyControls.getByRole('button', { name: /^Undo(?:\b|:)/, includeHidden: true })
  const redo = historyControls.getByRole('button', { name: /^Redo(?:\b|:)/, includeHidden: true })
  await expect(historyButton).toBeVisible()

  await historyButton.click()
  const historyDialog = page.getByRole('dialog', { name: 'History' })
  await expect(historyDialog).toBeVisible()
  await expect(historyDialog).toContainText('not a complete audit log')
  await expect(historyDialog).toContainText('initial baseline')
  await expect(undo).toBeDisabled()
  await expect(redo).toBeDisabled()
  await page.keyboard.press('Escape')
  await expect(historyDialog).toBeHidden()
  await expect(historyButton).toBeFocused()

  const details = await openChartDetails(page)
  await details.getByRole('button', { name: 'Edit chart names' }).click()
  const names = page.getByRole('dialog', { name: 'Edit chart names' })
  await names.getByLabel('Star system', { exact: true }).fill('Vesper Prime')
  await names.getByRole('button', { name: 'Apply names', exact: true }).click()
  await expect(names).toBeHidden()
  const closeInspector = page.getByRole('button', { name: 'Close inspector panel', exact: true })
  if (await closeInspector.isVisible()) await closeInspector.click()
  await expect(undo).toBeEnabled()
  await expect(redo).toBeDisabled()
  const undoLabelBeforeConsultation = await undo.getAttribute('aria-label')
  expect(undoLabelBeforeConsultation ?? '').toContain('Rename Jump Cluster and star system')
  const activeSystemMap = page.getByRole('group', { name: 'Vesper Prime star system map', exact: true })
  await expect(activeSystemMap).toBeVisible()

  const actionLabel = 'Rename Jump Cluster and star system'
  await historyButton.click()
  const retainedActions = historyDialog.getByRole('list', { name: 'Retained actions in chronological order' })
  await expect(retainedActions).toContainText(actionLabel)
  await expect(retainedActions).toContainText('Applied')
  const retainedActionText = await retainedActions.innerText()
  const positionSummary = historyDialog.getByText('1 available to undo · 0 available through Redo', { exact: true })
  await expect(positionSummary).toBeVisible()
  const positionSummaryText = await positionSummary.innerText()
  await expect(historyDialog.getByRole('status', { name: 'Current history position' })).toBeVisible()
  await expect(undo).toBeDisabled()
  await expect(redo).toBeDisabled()
  await expect(historyControls).toContainText('Close History before using Undo or Redo.')
  const bounds = await historyDialog.boundingBox()
  expect(bounds).not.toBeNull()
  if (!bounds) throw new Error('The history view is not visible.')
  expect(bounds.x).toBeGreaterThanOrEqual(0)
  expect(bounds.x + bounds.width).toBeLessThanOrEqual(390)
  expect(bounds.y + bounds.height).toBeLessThanOrEqual(844)
  await page.keyboard.press('Escape')
  await expect(historyDialog).toBeHidden()
  await expect(undo).toBeEnabled()
  await expect(redo).toBeDisabled()
  await expect(undo).toHaveAttribute('aria-label', undoLabelBeforeConsultation ?? '')
  await expect(activeSystemMap).toBeVisible()
  await expect(historyButton).toBeFocused()

  await historyButton.click()
  await expect.poll(() => retainedActions.innerText()).toBe(retainedActionText)
  await expect(historyDialog.getByText('1 available to undo · 0 available through Redo', { exact: true })).toHaveText(positionSummaryText)
  await page.keyboard.press('Escape')
  await expect(historyDialog).toBeHidden()
  await expect(activeSystemMap).toBeVisible()

  await undo.click()
  await expect(page.getByRole('navigation', { name: 'Map context and commands' }).getByRole('heading', { name: 'Kestrel Reach', exact: true })).toBeVisible()
  await expect(redo).toBeEnabled()
  await historyButton.click()
  await expect(retainedActions).toContainText(actionLabel)
  await expect(retainedActions).toContainText('Available through Redo')
  await expect(historyDialog.getByRole('status', { name: 'Current history position' })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(redo).toBeEnabled()
  await expect(historyButton).toBeFocused()
  await redo.click()
  await expect(undo).toBeEnabled()
})

test('History remains available while an Inspector draft blocks traversal and leaves the draft intact', async ({ page }) => {
  await createSingleSystemWorkspace(page)
  const details = await openChartDetails(page)
  await details.getByRole('button', { name: 'Edit chart names' }).click()
  const names = page.getByRole('dialog', { name: 'Edit chart names' })
  await names.getByLabel('Star system', { exact: true }).fill('Vesper Prime')
  await names.getByRole('button', { name: 'Apply names', exact: true }).click()
  await expect(names).toBeHidden()
  await returnToClusterMap(page)

  const clusterMap = page.getByRole('group', { name: 'Kestrel Reach Jump Cluster map', exact: true })
  await clusterMap.getByRole('button', { name: /^(Open|Select) Vesper Prime system(?: map)?$/ }).click()
  await page.getByRole('button', { name: 'Open system', exact: true }).click()
  const systemMap = page.getByRole('group', { name: 'Vesper Prime star system map', exact: true })
  await expect(systemMap).toBeVisible()
  await systemMap.getByRole('button', { name: /^Select .*Primary Star/ }).click()
  const inspect = page.getByRole('button', { name: 'Inspect', exact: true })
  if (await inspect.getAttribute('aria-expanded') !== 'true') await inspect.click()
  const inspector = page.getByRole('region', { name: 'Object inspector' })
  await expect(inspector.getByRole('heading', { name: 'Primary Star', exact: true })).toBeVisible()
  await inspector.getByRole('button', { name: 'Edit map object', exact: true }).click()
  await inspector.getByLabel('Name', { exact: true }).fill('Unapplied Star Name')

  const historyControls = page.locator('.workspace-history-controls')
  const undo = historyControls.getByRole('button', { name: /^Undo(?:\b|:)/, includeHidden: true })
  const historyButton = page.getByRole('button', { name: 'History', exact: true })
  await expect(undo).toBeDisabled()
  await expect(page.getByRole('group', { name: 'Edit history' })).toContainText('Apply or discard the modified Inspector draft first.')
  await historyButton.click()
  const historyDialog = page.getByRole('dialog', { name: 'History' })
  await expect(historyDialog.getByRole('list', { name: 'Retained actions in chronological order' })).toContainText('Rename Jump Cluster and star system')
  await expect(undo).toBeDisabled()
  await page.keyboard.press('Escape')
  await expect(inspector.getByLabel('Name', { exact: true })).toHaveValue('Unapplied Star Name')
  await expect(undo).toBeDisabled()
})

test('Undo from the Cluster opens the affected system and keeps the restored object selectable', async ({ page }) => {
  await createSingleSystemWorkspace(page)
  const map = page.getByRole('group', { name: 'Vesper star system map', exact: true })
  await map.getByRole('button', { name: /^Select .*Primary Star/ }).click()
  const inspect = page.getByRole('button', { name: 'Inspect', exact: true })
  if (await inspect.getAttribute('aria-expanded') !== 'true') await inspect.click()
  const inspector = page.getByRole('region', { name: 'Object inspector' })
  await inspector.getByRole('button', { name: 'Edit map object', exact: true }).click()
  await inspector.getByLabel('Name', { exact: true }).fill('Kepler Star')
  await inspector.getByRole('button', { name: 'Apply changes' }).click()
  await expect(inspector.getByRole('heading', { name: 'Kepler Star', exact: true })).toBeVisible()
  const zoom = (await workspaceZoomOutput(page).textContent())?.trim()
  await panMap(page, map, { x: 680, y: 340 })
  const targetBeforeTraversal = await map.getByRole('button', { name: /^Select .*Kepler Star/ }).boundingBox()
  const mapBoundsBeforeTraversal = await map.boundingBox()
  if (!targetBeforeTraversal || !mapBoundsBeforeTraversal) throw new Error('The edited object map bounds are unavailable.')
  const targetCenterX = targetBeforeTraversal.x + targetBeforeTraversal.width / 2
  const targetCenterY = targetBeforeTraversal.y + targetBeforeTraversal.height / 2
  expect(targetCenterX < mapBoundsBeforeTraversal.x
    || targetCenterX > mapBoundsBeforeTraversal.x + mapBoundsBeforeTraversal.width
    || targetCenterY < mapBoundsBeforeTraversal.y
    || targetCenterY > mapBoundsBeforeTraversal.y + mapBoundsBeforeTraversal.height).toBe(true)
  await returnToClusterMap(page)

  const undo = page.locator('.workspace-history-controls').getByRole('button', { name: /^Undo(?:\b|:)/ })
  await expect(undo).toBeEnabled()
  await undo.click()
  await expect(page.getByRole('navigation', { name: 'Map context and commands' }).locator('.workspace-map-context > span')).toHaveText('Star System')
  const restoredMap = page.getByRole('group', { name: 'Vesper star system map', exact: true })
  await expect(restoredMap).toBeVisible()
  await expect(restoredMap.getByRole('button', { name: /^Select .*Primary Star/ })).toBeVisible()
  await expect.poll(() => restoredMap.evaluate(map => document.activeElement === map)).toBe(true)
  const restoredTargetBounds = await restoredMap.getByRole('button', { name: /^Select .*Primary Star/ }).boundingBox()
  const restoredMapBounds = await restoredMap.boundingBox()
  expect(restoredTargetBounds).not.toBeNull()
  expect(restoredMapBounds).not.toBeNull()
  if (!restoredTargetBounds || !restoredMapBounds) throw new Error('The restored object map bounds are unavailable.')
  expect(restoredTargetBounds.x + restoredTargetBounds.width / 2).toBeGreaterThanOrEqual(restoredMapBounds.x)
  expect(restoredTargetBounds.x + restoredTargetBounds.width / 2).toBeLessThanOrEqual(restoredMapBounds.x + restoredMapBounds.width)
  expect(restoredTargetBounds.y + restoredTargetBounds.height / 2).toBeGreaterThanOrEqual(restoredMapBounds.y)
  expect(restoredTargetBounds.y + restoredTargetBounds.height / 2).toBeLessThanOrEqual(restoredMapBounds.y + restoredMapBounds.height)
  await expect(workspaceZoomOutput(page)).toHaveText(zoom ?? '100%')
  const redo = page.locator('.workspace-history-controls').getByRole('button', { name: /^Redo(?:\b|:)/ })
  await expect(redo).toBeEnabled()

  const inspectAfterUndo = page.getByRole('button', { name: 'Inspect', exact: true })
  if (await inspectAfterUndo.getAttribute('aria-expanded') !== 'true') await inspectAfterUndo.click()
  const inspectorAfterUndo = page.getByRole('region', { name: 'Object inspector' })
  await expect(inspectorAfterUndo.getByRole('heading', { name: 'Primary Star', exact: true })).toBeVisible()
})

test('Undo of a new object from the Cluster falls back to its surviving system', async ({ page }) => {
  await createSingleSystemWorkspace(page)
  await addCatalogueObject(page, 'planet')
  await returnToClusterMap(page)

  const undo = page.locator('.workspace-history-controls').getByRole('button', { name: /^Undo(?:\b|:)/ })
  await expect(undo).toBeEnabled()
  await undo.click()

  const systemMap = page.getByRole('group', { name: 'Vesper star system map', exact: true })
  await expect(systemMap).toBeVisible()
  await expect(systemMap.getByRole('button', { name: /^Select .*Primary Star/ })).toBeVisible()
  await expect(systemMap.locator('.system-object')).toHaveCount(1)
  await expect(systemMap.getByRole('button', { name: /New planet/i })).toHaveCount(0)
})

test('Undo of an Orbit edit from the Cluster restores its system and selects the Orbit', async ({ page }) => {
  await createSingleSystemWorkspace(page)
  await clickDockAction(page, 'Add orbit', { target: { kind: 'center', x: 0.25, y: 0.25 } })

  const orbitLabel = /Orbit 1 around unoccupied center/
  const hierarchy = page.getByRole('complementary', { name: 'System hierarchy' })
  const orbit = hierarchy.getByRole('button', { name: orbitLabel })
  await expect(orbit).toBeVisible()
  await expect(orbit).toHaveAttribute('aria-current', 'true')
  const map = page.getByRole('group', { name: 'Vesper star system map', exact: true })
  const originalRadius = await map.getByRole('group', { name: orbitLabel }).locator('.orbit-ring').getAttribute('rx')

  await page.getByRole('button', { name: 'Edit Orbit', exact: true }).click()
  await page.getByRole('spinbutton', { name: 'Horizontal radius', exact: true }).fill('280')
  await page.getByRole('button', { name: 'Save Orbit' }).click()
  await expect(map.getByRole('group', { name: orbitLabel }).locator('.orbit-ring')).toHaveAttribute('rx', '280')
  await returnToClusterMap(page)

  const undo = page.locator('.workspace-history-controls').getByRole('button', { name: /^Undo(?:\b|:)/ })
  await undo.click()

  const restoredMap = page.getByRole('group', { name: 'Vesper star system map', exact: true })
  await expect(restoredMap).toBeVisible()
  const restoredOrbit = page.getByRole('complementary', { name: 'System hierarchy' }).getByRole('button', { name: orbitLabel })
  await expect(restoredOrbit).toHaveAttribute('aria-current', 'true')
  await expect(restoredMap.getByRole('group', { name: orbitLabel }).locator('.orbit-ring')).toHaveAttribute('rx', originalRadius ?? '')
})
